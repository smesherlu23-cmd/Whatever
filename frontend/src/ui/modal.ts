/**
 * Открыто модальное окно. Страница под ним недоступна, поэтому клавиши, которые слушает вся
 * страница, достаются окну: Esc закрывает окно, а не снимает выделение на доске под ним.
 * Окна приложения открываются только модально (см. Dialog), поэтому хватает открытого <dialog>.
 */
export function modalDialogOpen(): boolean {
  return document.querySelector('dialog[open]') !== null;
}
