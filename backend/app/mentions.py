"""Упоминания коллег в комментариях: @логин в тексте.

Логин может содержать точку, дефис и @ (например, ivan.petrov или ivan@corp), поэтому
упоминание заканчивается буквой, цифрой или подчёркиванием: точка после «@ivan.» — конец
предложения, а не часть логина. Перед @ не должно быть символа логина, иначе это адрес почты
в тексте, а не упоминание. Фронтенд выделяет упоминания по тому же правилу.
"""

import re

MENTION = re.compile(r"(?<![A-Za-z0-9._@-])@([A-Za-z0-9._@-]*[A-Za-z0-9_])")


def mentioned_logins(text: str) -> set[str]:
    """Логины, упомянутые в тексте, в нижнем регистре, как они хранятся в базе."""
    return {match.lower() for match in MENTION.findall(text)}
